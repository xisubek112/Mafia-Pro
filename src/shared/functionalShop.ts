export function isFunctionalCategory(cat: string): cat is FunctionalItemCategory {
  return (FUNCTIONAL_CATEGORY_SLUGS as string[]).includes(cat);
}

export function isLegacyCosmeticCategory(cat: string): boolean {
  return LEGACY_COSMETIC_SLUGS.has(cat);
}

